"""Spread of the split across the four decomposition methods.

# ! NOTE -- "split range", never "error": no experiment tells the four methods apart.

Produces: results/6b_cross_term_split__<dataset_label>.md
"""

import sys
from datetime import datetime
from pathlib import Path

import arviz as az
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from config.diagnostics import SPLIT_TABLE_DECIMALS  # noqa: E402
from config.idata_paths import require_idata  # noqa: E402
from synthetic_data.true_params_reader import get_dataset_label, warn_if_idata_stale  # noqa: E402
import viz.decomposition as D  # noqa: E402
from viz.io import provenance_fields  # noqa: E402
from viz.business import canonical_slice  # noqa: E402

DATASET_LABEL = get_dataset_label()
if DATASET_LABEL != "log__no_noise":
    sys.exit(f"6b_: this bench is ONLY for the no-noise regime. The live dataset is {DATASET_LABEL!r}; "
             f"regenerate the dataset with step 1 of the README.")
IDATA_PATH = require_idata("linear_trend", DATASET_LABEL)
warn_if_idata_stale(IDATA_PATH)
idata = az.from_netcdf(IDATA_PATH)
dfm = canonical_slice()
OUTPUT = ROOT / "results" / f"6b_cross_term_split__{DATASET_LABEL}.md"
LABEL = {"log_price_c": "price", "promo_flag": "promo", "log_acv_c": "ACV", "t_norm_c": "trend",
         "seasonality": "seasonality", "tv": "tv", "meta": "meta", "tiktok": "tiktok", "ooh": "ooh"}


def split(reference: str) -> dict:
    fv = D.ValueFunction.from_components(D.model_components(idata, reference, dfm))
    V = fv.total(fv.N)
    pct = lambda x: float(np.mean(100 * x / V))  # noqa: E731  # trivial: unit
    A = D.removal(fv)
    B = D.sequential(fv, D.BASE_ORDER_K9)
    C = D.shapley(fv)
    Dm = D.lmdi(fv)
    R = D.sequential_range(fv, normalize=pct)
    rows = {k: {"A": pct(A[k]), "B": pct(B[k]), "Bmin": R[k][0], "Bmax": R[k][1],
                "C": pct(C[k]), "D": pct(Dm[k])} for k in fv.names}
    for k, r in rows.items():   # the range has to contain (B) in any order and (C)
        assert r["Bmin"] - 1e-9 <= r["B"] <= r["Bmax"] + 1e-9, k  # trivial: floating-point tolerance
        assert r["Bmin"] - 1e-9 <= r["C"] <= r["Bmax"] + 1e-9, k  # trivial: floating-point tolerance
    joint = pct(fv.incremental())
    closing = {
        "sum": {m: sum(rows[k][m] for k in fv.names) for m in ("A", "B", "C", "D")},
        "joint": joint,
        "base": pct(fv.total(0)),
    }
    for m in ("B", "C", "D"):
        assert abs(closing["sum"][m] - joint) < 1e-8, (reference, m)  # trivial: floating-point tolerance
    lev = D.reference_levels(reference, dfm)
    return {"rows": rows, "closing": closing, "levels": lev, "order": fv.names}


def table(headers, rows):
    widths = [max(len(str(h)), *(len(str(f[i])) for f in rows)) for i, h in enumerate(headers)]
    out = ["| " + " | ".join(str(h).ljust(a) for h, a in zip(headers, widths)) + " |",
           "|" + "|".join("-" * (a + 2) for a in widths) + "|"]  # cosmetic
    out += ["| " + " | ".join(str(c).ljust(a) for c, a in zip(f, widths)) + " |" for f in rows]
    return out


def block(res, title) -> list:
    f, c = res["rows"], res["closing"]
    body = [[LABEL[k], f"{f[k]['A']:.3f}", f"{f[k]['B']:.3f}", f"{f[k]['Bmin']:.3f}",
             f"{f[k]['Bmax']:.3f}", f"{f[k]['C']:.3f}", f"{f[k]['D']:.3f}"] for k in res["order"]]
    body += [
        ["**sum**", f"{c['sum']['A']:.3f}", f"{c['sum']['B']:.3f}", "—", "—",
         f"{c['sum']['C']:.3f}", f"{c['sum']['D']:.3f}"],
        ["**joint effect**", f"{c['joint']:.3f}", f"{c['joint']:.3f}", "—", "—",
         f"{c['joint']:.3f}", f"{c['joint']:.3f}"],
        ["**cross**", f"{c['sum']['A'] - c['joint']:.3f}", "0", "—", "—", "0", "0"],
    ]
    n = res["levels"]
    return ([f"## {title}", "",
             f"Price taken to **{n['price']:.4f}** and ACV to **{n['acv']:.4f}**. "
             f"The base —every driver at its reference— is **{c['base']:.3f}%** of the period's sales.",
             "",
             "This whole table, closing rows included, comes from the **model posterior** with that reference: "
             "the **sum** is that of its own column (A), and the **joint effect** is its `v(N) − v(∅)`. There is "
             "no DGP column here — the model against DGP comparison is the one in "
             "`6a_cross_term__<dataset_label>.md`, which also groups to K=8.",
             ""] +
            table(["Driver", "(A) removal", "(B) base order", "(B) min", "(B) max", "(C) Shapley", "(D) LMDI"],
                  body) + [""])


def main():
    mod, dgp = split("model"), split("dgp")
    prov = provenance_fields("linear_trend")
    L = [
        "# Split of sales across drivers — four methods, two references",
        "",
        "GENERATED by `model/6_cross_term/6b_cross_term_split.py` — **do not edit by hand**.",
        "",
        f"> **Provenance:** dataset=`{DATASET_LABEL}` | idata=`{prov['idata_name']}`@`{prov['idata_hash']}` "
        f"| csv=`{prov['csv_name']}`@`{prov['csv_hash']}` | commit=`{prov['commit']}` "
        f"| generated {datetime.now().isoformat(timespec='seconds')}",
        "",
        "> **What it claims and what it does not.** It shows HOW the same model is split with four different",
        "> rules. The difference between (B), (C) and (D) is **split range**, not error: the split of the cross",
        "> term is not a parameter of the generator and no experiment tells it apart. No method is better than",
        "> another on this dimension. And since the priors were chosen by whoever wrote the generator, none of this says how precise the",
        "> model is.",
        "",
        "Everything in **% of the period's sales** (156 weeks, `Geo_Centro` · `Retail`), mean over the draws.",
        "Each method is computed week by week and then summed. (A) does not add up to the joint effect; the",
        "**cross** row is what it is missing. (B), (C) and (D) add up exactly by construction.",
        "",
        "- **(B) base order:** price → promo → ACV → trend → seasonality → tv → meta → tiktok → ooh.",
        "- **(B) min / max:** the range of (B) over the 9! possible orders, exact (256 subsets per driver).",
        "- **(D) LMDI:** weekly, with logarithmic mean `L(Ŷ, base)·ln f_k`.",
        "",
    ]
    L += block(mod, "1. MODEL reference — price and ACV at their geometric mean")
    L += block(dgp, "2. DGP reference — price and ACV at 100")
    body = []
    for k in mod["order"]:
        a, b = mod["rows"][k], dgp["rows"][k]
        d = lambda x: f"{round(x, 6) + 0.0:+.{SPLIT_TABLE_DECIMALS}f}"  # noqa: E731  # trivial: 6 avoids the "-0.000"
        body.append([LABEL[k]] + [d(b[m] - a[m]) for m in ("A", "B", "C", "D")] +
                    [d((b['Bmax'] - b['Bmin']) - (a['Bmax'] - a['Bmin']))])
    body.append(["**base**", f"{dgp['closing']['base'] - mod['closing']['base']:+.3f}", "", "", "", ""])
    L += ["## 3. How much the split moves when the reference changes", "",
          "DGP reference minus model reference, in points of % of sales. Media, promo, trend and",
          "seasonality do **not** change reference: if they move it is because the base they are measured",
          "against changed.", ""]
    L += table(["Driver", "Δ(A)", "Δ(B) base order", "Δ(C)", "Δ(D)", "Δ width of the (B) range"], body)
    OUTPUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"  {OUTPUT.relative_to(ROOT).as_posix()}")


if __name__ == "__main__":
    main()
