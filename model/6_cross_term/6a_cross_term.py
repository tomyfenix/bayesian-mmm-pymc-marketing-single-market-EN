"""The cross term of the decomposition, in the model and in the generator.

# ! NOTE -- this is not model precision: the priors were chosen by whoever wrote the generator.
# ! NOTE -- ACV = 100 is outside the observed support; the maximum of the period is 96.

Produces: results/6a_cross_term__<dataset_label>.md
"""

import math
import sys
from datetime import datetime
from pathlib import Path

import arviz as az
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from config.idata_paths import require_idata  # noqa: E402
from synthetic_data.true_params_reader import get_dataset_label, warn_if_idata_stale  # noqa: E402
import viz.decomposition as D  # noqa: E402
from viz.io import provenance_fields  # noqa: E402
from viz.business import canonical_slice  # noqa: E402

DATASET_LABEL = get_dataset_label()
if DATASET_LABEL != "log__no_noise":
    sys.exit(f"6a_: this bench is ONLY for the no-noise regime. The live dataset is {DATASET_LABEL!r}; "
             f"regenerate the dataset with step 1 of the README.")
IDATA_PATH = require_idata("linear_trend", DATASET_LABEL)
warn_if_idata_stale(IDATA_PATH)
idata = az.from_netcdf(IDATA_PATH)
dfm = canonical_slice()
OUTPUT = ROOT / "results" / f"6a_cross_term__{DATASET_LABEL}.md"
MEDIA = ["tv", "meta", "tiktok", "ooh"]


def media_cross(fv, pct):
    """Sum of the individual media removals, joint media effect and relative excess."""
    A = D.removal(fv)
    no_media = fv.N
    for k in MEDIA:
        no_media &= ~(1 << fv.names.index(k))
    joint = pct(fv.total(fv.N) - fv.total(no_media))
    total = sum(pct(A[k]) for k in MEDIA)
    return total, joint, 100 * (total - joint) / joint  # trivial: unit


def k_cross(fv, pct):
    A = D.removal(fv)
    total = sum(pct(A[k]) for k in fv.names)
    joint = pct(fv.incremental())
    return total, joint, total - joint, 100 * (total - joint) / joint  # trivial: unit


def main():
    # percentage of the period's sales: per draw, then the mean (the model has 4000 draws)
    comp_m = D.model_components(idata, "dgp", dfm)
    fvm = D.ValueFunction.from_components(comp_m)
    Vm = fvm.total(fvm.N)
    pm = lambda x: float(np.mean(100 * x / Vm))  # noqa: E731  # trivial: unit
    fvd = D.ValueFunction.from_components(D.dgp_components("dgp", dfm))
    Vd = fvd.total(fvd.N)
    pd_ = lambda x: float(np.mean(100 * x / Vd))  # noqa: E731  # trivial: unit

    # 3.1 -- media do not depend on the reference: price and ACV stay switched on in both worlds
    ms, mc, mx = media_cross(fvm, pm)
    ds, dc, dx = media_cross(fvd, pd_)

    # 3.2 -- K=8 on the model side (EXPLICIT grouping) against K=8 of the DGP, reference 100/100
    fvg = D.ValueFunction.from_components(D.group(comp_m, D.GROUPING_K8))
    Vg = fvg.total(fvg.N)
    pg = lambda x: float(np.mean(100 * x / Vg))  # noqa: E731  # trivial: unit
    ks_m = k_cross(fvg, pg)
    ks_d = k_cross(fvd, pd_)

    # 3.3 -- the ACV extrapolation warning with reference 100
    acv = dfm["acv"].values
    cap = acv.max()   # the observed maximum of the period (96 in the canonical dataset)
    above_96 = int((acv > cap).sum())
    at_96 = int((acv >= cap).sum())
    frac_level = (100 - acv.max()) / (100 - acv.min())  # trivial: unit
    frac_log = math.log(100 / acv.max()) / math.log(100 / acv.min())  # trivial: unit
    per_week = np.log(100 / acv.max()) / np.log(100 / acv)  # trivial: unit
    price = dfm["price"].values

    prov = provenance_fields("linear_trend")
    L = [
        "# Cross term of the decomposition — model against DGP",
        "",
        "GENERATED by `model/6_cross_term/6a_cross_term.py` — **do not edit by hand**.",
        "",
        f"> **Provenance:** dataset=`{DATASET_LABEL}` | idata=`{prov['idata_name']}`@`{prov['idata_hash']}` "
        f"| csv=`{prov['csv_name']}`@`{prov['csv_hash']}` | commit=`{prov['commit']}` "
        f"| draws={len(Vm)} | generated {datetime.now().isoformat(timespec='seconds')}",
        "",
        "> **READ BEFORE CITING.** The priors were chosen by whoever wrote the generator. The closeness between",
        "> the model column and the DGP column is **optimistic by construction** and is NOT a measure of precision.",
        "> All this table claims is that **the overlap exists and has this size**.",
        "",
        "Everything in **% of the period's sales** (156 weeks, `Geo_Centro` · `Retail`). The model is the mean",
        "over the draws of each draw's percentage.",
        "",
        "## 1. Media only — it does not depend on any reference",
        "",
        "Price and ACV stay switched on in both worlds being compared, so their reference level does not",
        "come in.",
        "",
    ]
    L += D_table(["Quantity", "Model", "DGP"], [
        ["sum of removals", f"{ms:.3f}", f"{ds:.3f}"],
        ["joint effect", f"{mc:.3f}", f"{dc:.3f}"],
        ["cross (pp)", f"{ms - mc:.3f}", f"{ds - dc:.3f}"],
        ["excess over joint (%)", f"{mx:.2f}", f"{dx:.2f}"],
    ])
    L += [
        "",
        "## 2. The K=8 drivers — DGP reference (price 100, ACV 100) on both sides",
        "",
        "On the model side, `t_norm_c` and `seasonality` are grouped EXPLICITLY into `trend + seasonality`",
        "(`viz.decomposition.GROUPING_K8`): the DGP puts the trend inside the seasonality and it is a",
        "single factor. It is the only common reference: the DGP has no other.",
        "",
    ]
    L += D_table(["Quantity", "Model", "DGP"], [
        ["sum of removals", f"{ks_m[0]:.3f}", f"{ks_d[0]:.3f}"],
        ["joint effect", f"{ks_m[1]:.3f}", f"{ks_d[1]:.3f}"],
        ["cross (pp)", f"{ks_m[2]:.3f}", f"{ks_d[2]:.3f}"],
        ["excess over joint (%)", f"{ks_m[3]:.2f}", f"{ks_d[3]:.2f}"],
    ])
    L += [
        "",
        "## 3. The extrapolation warning that goes with table 2",
        "",
        f"The DGP reference takes ACV to **100**, and the ACV of the period goes from {acv.min():.2f} to {acv.max():.2f}.",
        "",
    ]
    L += D_table(["Quantity", "Value"], [
        [f"weeks with ACV > {cap:g}", f"{above_96} of {len(acv)}"],
        [f"weeks with ACV = {cap:g}", f"{at_96} of {len(acv)}"],
        [f"stretch {cap:g}-100 / range {acv.min():g}-100 (levels)", f"{100 * frac_level:.1f}%"],  # trivial: ACV in %
        [f"stretch {cap:g}-100 / range {acv.min():g}-100 (log)", f"{100 * frac_log:.1f}%"],  # trivial: ACV in %
        ["path to 100 extrapolated, mean per week", f"{100 * per_week.mean():.1f}%"],  # trivial: unit
        ["path to 100 extrapolated, worst week", f"{100 * per_week.max():.1f}%"],  # trivial: unit
        ["price 100 within what was observed", f"yes ({price.min():.2f} to {price.max():.2f})"],
    ])
    L += [
        "",
        "The last ACV row is the one that matters: in the week with ACV = 96 **the whole** path to the",
        "reference is outside what was observed. There the DGP's ACV factor is the functional form",
        "`(ACV/100)^e` evaluated where there never were data, and the model's is its extrapolated elasticity.",
    ]
    OUTPUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"  {OUTPUT.relative_to(ROOT).as_posix()}")
    print(f"  3.1 media: model {mx:.2f}%  DGP {dx:.2f}%")
    print(f"  3.2 K=8, dgp ref: model cross {ks_m[2]:.3f} pp ({ks_m[3]:.2f}%)  DGP {ks_d[2]:.3f} pp ({ks_d[3]:.2f}%)")
    print(f"  3.3 ACV>{cap:g}: {above_96}; extrapolated stretch {100 * frac_level:.1f}% (levels), "  # trivial: unit
          f"{100 * frac_log:.1f}% (log); per week mean {100 * per_week.mean():.1f}% max {100 * per_week.max():.1f}%")  # trivial: unit


def D_table(headers, rows):
    widths = [max(len(str(h)), *(len(str(f[i])) for f in rows)) for i, h in enumerate(headers)]
    out = ["| " + " | ".join(str(h).ljust(a) for h, a in zip(headers, widths)) + " |",
           "|" + "|".join("-" * (a + 2) for a in widths) + "|"]  # cosmetic
    out += ["| " + " | ".join(str(c).ljust(a) for c, a in zip(f, widths)) + " |" for f in rows]
    return out


if __name__ == "__main__":
    main()
