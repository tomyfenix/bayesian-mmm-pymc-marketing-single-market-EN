"""Saving figures: resolves the path with the project's naming convention and stamps the provenance at
the bottom (hash of the .nc, hash of the CSV and the commit it was generated from). The CSV one is the
sha256 of its CONTENT (config.contracts.content_sha256, line endings in LF), the same one as in the
manifest and the truth JSON: it is the same on Windows and on Linux. The .nc one, binary, is of bytes.
"""

import hashlib
import subprocess
from datetime import datetime
from pathlib import Path

from config.dataset_sync import GENERATOR_ARTIFACTS

_ROOT = Path(__file__).resolve().parents[1]

_HASH_CACHE: dict[str, str] = {}


def figure_path(root: Path, stage_dir: str, stub: str, dataset_label: str) -> Path:
    """`stub` already includes the <stage><letter><n>_<name> prefix (e.g. "3b1_convergence"). Returns
    root/model/<stage_dir>/plots/<stub>__<dataset_label>.png, without creating the file -- only the path.
    """
    return root / "model" / stage_dir / "plots" / f"{stub}__{dataset_label}.png"


def _sha256_short(path: Path, n: int = 8) -> str:  # cosmetic
    """sha256 of the bytes, for the .nc (binary: it has no line endings to normalize)."""
    key = str(path)
    if key not in _HASH_CACHE:
        h = hashlib.sha256()
        with open(path, "rb") as f:
            for chunk in iter(lambda: f.read(1 << 20), b""):  # trivial: infrastructure: file reading and git timeout
                h.update(chunk)
        _HASH_CACHE[key] = h.hexdigest()[:n]
    return _HASH_CACHE[key]


STAMP_STRIP_IN = 0.30  # cosmetic

# Dataset CSV: the single source the .nc comes from. Its hash goes in the stamp.
_CSV_PATH = _ROOT / "synthetic_data" / "dataset.csv"

GENERATED_MARKER = "do not edit by hand"

GENERATED_DIRS = {"plots", "_saved", "_archive", "_scaffolding"}

# Extensions that in this repo are always a rendered artifact, never a source.
GENERATED_SUFFIXES = {".png"}


def is_generated_artifact(rel_path: str) -> bool:
    """True if `rel_path` (relative to the repo root) is an artifact GENERATED by a script, not a
    source file.
    """
    path = Path(rel_path)
    if GENERATED_DIRS & set(path.parts):
        return True
    if path.suffix.lower() in GENERATED_SUFFIXES:
        return True
    if path.as_posix() in GENERATOR_ARTIFACTS:
        return True
    abs_path = _ROOT / path
    try:
        if abs_path.is_file():
            with open(abs_path, "r", encoding="utf-8", errors="ignore") as f:
                head = f.read(2048)  # trivial: infrastructure: file reading and git timeout
            return GENERATED_MARKER in head.lower()
    except OSError:
        pass
    return False


def _dirty_source_paths() -> list[str]:
    """Paths with uncommitted changes that are NOT generated artifacts. Empty list => the tree is clean
    as far as the CODE is concerned.
    """
    status = subprocess.run(
        ["git", "status", "--porcelain"], cwd=_ROOT,
        capture_output=True, text=True, timeout=5,  # trivial: infrastructure: file reading and git timeout
    )
    if status.returncode != 0:
        return []
    dirty = []
    for line in status.stdout.splitlines():
        if not line.strip():
            continue
        payload = line[3:] if len(line) > 3 else ""  # trivial: text parsing
        # renames come as "old -> new": both sides count
        candidates = [c.strip().strip('"') for c in payload.split(" -> ")] if " -> " in payload else [payload.strip().strip('"')]
        if any(not is_generated_artifact(c) for c in candidates if c):
            dirty.append(payload.strip())
    return dirty


def git_commit_short() -> str:
    """Short git hash, with a -dirty suffix if there are uncommitted changes IN SOURCE FILES. "no-git"
    if there is no repo or git is not available -- it never fails, it is never empty.
    """
    try:
        rev = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], cwd=_ROOT,
            capture_output=True, text=True, timeout=5,  # trivial: infrastructure: file reading and git timeout
        )
        if rev.returncode != 0:
            return "no-git"
        commit = rev.stdout.strip()
        if _dirty_source_paths():
            return f"{commit}-dirty"
        return commit
    except (FileNotFoundError, OSError, subprocess.SubprocessError):
        return "no-git"


def provenance_fields(idata_name: str | tuple[str, ...] | None = "linear_trend") -> dict:
    """Gathers the stamp fields in a dict -- used both by stamp_figure() (footer of each PNG) and by the
    .md tables of results/, so that they say exactly the same about the same run.
    """
    import sys
    if str(_ROOT) not in sys.path:
        sys.path.insert(0, str(_ROOT))
    from synthetic_data.true_params_reader import get_dataset_label
    from config.idata_paths import idata_path as _idata_path_fn
    from config.dataset_sync import check_sync

    label = get_dataset_label()
    names = (() if idata_name is None else
             (idata_name,) if isinstance(idata_name, str) else tuple(idata_name))
    ipaths = [_idata_path_fn(n, label) for n in names]
    idatas = [(p.name, _sha256_short(p) if p.exists() else "missing") for p in ipaths]

    cpath = _CSV_PATH
    from config.contracts import content_sha256
    chash = content_sha256(cpath)[:8] if cpath.exists() else "missing"  # cosmetic

    sync = [check_sync(p, cpath) for p in ipaths]
    out_of_sync = any(d for d, _m in sync)
    sync_reason = "; ".join(m for _d, m in sync) or "not applicable: the figure reads no .nc"

    # the stamp says the regime, READ from the dataset (config.contracts). If it cannot be read, it
    # says so -- it does not make one up.
    try:
        from config.contracts import dataset_regime
        regime = dataset_regime()
    except Exception as exc:  # noqa: BLE001
        regime = f"unreadable ({type(exc).__name__})"

    return {
        "dataset_label": label,
        "regime": regime,
        "idata_name": "+".join(n for n, _h in idatas) or "none",
        "idata_hash": "+".join(h for _n, h in idatas) or "-",
        "idatas": idatas,
        "idata_path": "; ".join(str(p.relative_to(_ROOT)) if p.exists() else str(p) for p in ipaths) or "-",
        "csv_name": cpath.name,
        "csv_hash": chash,
        "dataset_out_of_sync": out_of_sync,
        "sync": sync_reason,
        "commit": git_commit_short(),
        "timestamp": datetime.now().isoformat(timespec="seconds"),
    }


def stamp_figure(fig, script_file, idata_name: str | tuple[str, ...] | None = "linear_trend",
                 dpi: float | None = None) -> str:
    """Stamps the provenance footer on `fig` and returns the stamped text. `dpi` is the saving one: the
    text width is measured at that dpi, because the relative width of a font changes with resolution.
    """
    from viz.style import INK_MUTED

    fields = provenance_fields(idata_name)
    idata_txt = ("idata=" + ", ".join(f"{n}@{h}" for n, h in fields["idatas"])
                 if fields["idatas"] else "idata=none")
    text = (
        f"dataset={fields['dataset_label']} | regime={fields['regime']} "
        f"| {idata_txt} "
        f"| csv={fields['csv_name']}@{fields['csv_hash']} "
        f"| commit={fields['commit']} | script={Path(script_file).name} | {fields['timestamp']}"
    )
    warning = "DATASET OUT OF SYNC | " if fields["dataset_out_of_sync"] else ""
    width_in, height_in = fig.get_size_inches()
    new_height = height_in + STAMP_STRIP_IN
    fig.set_size_inches(width_in, new_height, forward=True)

    # Relocate each axis: its position in figure coordinates is rescaled so that it takes the same
    # PHYSICAL space as before, now shifted up.
    scale = height_in / new_height
    shift = STAMP_STRIP_IN / new_height
    for ax in fig.axes:
        box = ax.get_position()
        ax.set_position([box.x0, box.y0 * scale + shift,
                         box.width, box.height * scale])

    from viz.style import MISS_COLOR

    y_stamp = (STAMP_STRIP_IN * 0.30) / new_height  # cosmetic

    def _renderer():
        """A renderer to MEASURE text, without drawing the whole figure. get_window_extent() only needs
        the renderer, not the drawn figure.
        """
        try:
            return fig.canvas.get_renderer()
        except AttributeError:
            fig.canvas.draw()
            return fig.canvas.get_renderer()

    def _draw(fs: float):
        """Draws the footer with font size `fs` and returns (artists, right edge as a fraction of the
        figure).
        """
        artists, x = [], 0.006  # cosmetic
        width_px = fig.get_figwidth() * fig.dpi
        r = _renderer()
        if warning:
            a = fig.text(x, y_stamp, warning, fontsize=fs + 1.0, color=MISS_COLOR,
                         weight="bold", ha="left", va="bottom")
            artists.append(a)
            x = a.get_window_extent(renderer=r).x1 / width_px
        p = fig.text(x, y_stamp, text, fontsize=fs, color=INK_MUTED, ha="left", va="bottom")
        artists.append(p)
        return artists, p.get_window_extent(renderer=r).x1 / width_px

    # The stamp grew (CSV hash, and the warning when it shows up) and no longer always fits at 6.5 pt in
    # narrow figures. It shrinks until it fits, instead of letting the right edge silently cut fields.
    # Floor 4.5 pt: below that it cannot be read and cutting is preferable.
    original_dpi = fig.dpi
    if dpi is not None:
        fig.set_dpi(dpi)
    fs = 6.5  # cosmetic
    while True:
        artists, edge = _draw(fs)
        if edge <= 0.985 or fs <= 4.5:  # cosmetic
            break
        for a in artists:
            a.remove()
        fs -= 0.25  # cosmetic
    if edge > 0.985:  # cosmetic
        # Not even at the floor does it fit in one line: it is split in two at the separator closest to the middle.
        for a in artists:
            a.remove()
        cuts = [i for i in range(len(text)) if text.startswith(" | ", i)]
        i = min(cuts, key=lambda c: abs(c - len(text) / 2))  # trivial: identity of the formula
        text = text[:i] + "\n" + text[i + 3:]  # trivial: text parsing
        fs = 6.0  # cosmetic
        while True:
            artists, edge = _draw(fs)
            if edge <= 0.985 or fs <= 4.5:  # cosmetic
                break
            for a in artists:
                a.remove()
            fs -= 0.25  # cosmetic
    fig.set_dpi(original_dpi)

    return warning + text


def save_figure(fig, path: Path, dpi: int = 150, *, script_file=None,  # cosmetic
                idata_name: str | tuple[str, ...] | None = "linear_trend") -> Path:
    """Defensive mkdir + provenance stamp (if `script_file` is given, which is how the figure scripts call
    it) + savefig + close.
    """
    if script_file is not None:
        stamp_figure(fig, script_file, idata_name=idata_name, dpi=dpi)
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=dpi)
    import matplotlib.pyplot as plt
    plt.close(fig)
    return path
